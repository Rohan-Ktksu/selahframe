"""Explicit developer smoke test: stop the web server before running this script."""

import argparse
import json
import sys
import time
from pathlib import Path

from fastapi.testclient import TestClient

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.main import app  # noqa: E402 - project root is added for direct script execution

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--quality", choices=["720p", "1080p"], default="720p")
parser.add_argument(
    "--full",
    action="store_true",
    help="Use a longer technical narration for a near-minute trial",
)
args = parser.parse_args()

# Exact public-domain input verified against the primary source on 2026-10-18.
source = "https://ebible.org/eng-web/PSA023.htm"
verse = "Yahweh is my shepherd; I shall lack nothing."
text = (
    "This is a SelahFrame technical preview using abstract placeholder scenes. "
    "Psalm twenty-three, verse one, in the World English Bible says: "
    + verse
    + " The voice is generated by a local speech model. "
    "The captions use approximate timing. Review every video before sharing it."
)

if args.full:
    text += (
        " We are checking a complete local workflow, from reviewed text to speech, image scenes, "
        "camera movement, readable subtitles, and a final downloadable file. "
        "These abstract shapes are intentionally labeled placeholders. Replace them with your own photographs "
        "or properly licensed artwork when you create a real project. "
        "The application saves the exact script version used for this export, along with the voice source and image licenses. "
        "This test also checks that sound continues to the end and that the picture stays in a vertical format. "
        "No background music has been added. The completed video remains on your computer until you choose to upload it."
    )

with TestClient(app) as client:
    response = client.post(
        "/api/v1/projects",
        json={
            "title": "Technical preview - Psalm 23:1",
            "reference": "Psalm 23:1",
            "scripture": verse,
            "translation": "World English Bible Classic",
            "scripture_source": source,
            "source_license": "Public domain; https://ebible.org/eng-web/copyright.htm",
            "context_text": "Verse 2: He makes me lie down in green pastures. He leads me beside still waters.",
            "placeholders": True,
        },
    )
    response.raise_for_status()
    pid = response.json()["id"]
    base = f"/api/v1/projects/{pid}"
    saved = client.put(base + "/script", json={"script": text})
    saved.raise_for_status()
    # Approval here is explicitly for this fixed technical test fixture, not user content.
    approved = client.post(
        base + "/script:approve",
        json={"script_version": saved.json()["script_version"]},
    )
    approved.raise_for_status()
    start = time.monotonic()
    queued = client.post(base + "/render", json={"quality": args.quality})
    queued.raise_for_status()
    job_id = queued.json()["job_id"]
    previous = None
    for _ in range(360):
        job = client.get("/api/v1/jobs/" + job_id).json()
        status = (job["stage"], job["status"], job["progress"])
        if status != previous:
            print(json.dumps(job), flush=True)
            previous = status
        if job["status"] in {"complete", "failed"}:
            break
        time.sleep(1)
    if job["status"] != "complete":
        raise SystemExit("SMOKE FAILED: " + job.get("error", "timeout"))
    preview = client.get(base + "/preview", headers={"Range": "bytes=0-1023"})
    if preview.status_code != 206 or len(preview.content) != 1024:
        raise SystemExit("MP4 range playback test failed")
    export = client.get(base + "/exports").json()[0]
    summary = {
        "project_id": pid,
        "job_id": job_id,
        "elapsed_seconds": round(time.monotonic() - start, 2),
        "export": export,
        "range_playback": preview.status_code,
        "video": str(ROOT / "output" / pid / "exports" / job_id / "final.mp4"),
    }
    (ROOT / "temp" / f"smoke-{args.quality}.json").write_text(
        json.dumps(summary, indent=2), encoding="utf-8"
    )
    print(json.dumps(summary, indent=2), flush=True)
